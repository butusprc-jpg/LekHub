create or replace function public.lekhub_digits_key(p_value text)
returns text language sql immutable strict
as $$
 select string_agg(ch,'' order by ch)
 from regexp_split_to_table(p_value,'') ch where ch<>'';
$$;

create or replace function public.lekhub_tenant_from_channel(
 p_channel_id text,p_require_ready boolean default true
) returns text language plpgsql security definer set search_path='public'
as $$
declare v public.lekhub_tenants%rowtype;
begin
 select * into v from public.lekhub_tenants
 where line_channel_id=nullif(trim(p_channel_id),'') limit 1;
 if not found then raise exception 'tenant_channel_not_found'; end if;
 if v.status<>'active' then raise exception 'tenant_inactive'; end if;
 if v.expires_at is not null and v.expires_at<=now() then raise exception 'tenant_expired'; end if;
 if p_require_ready and v.isolation_ready is not true then raise exception 'tenant_not_ready'; end if;
 return v.tenant_key;
end $$;

create or replace function public.lekhub_effective_round_date_for_tenant(
 p_tenant text,p_at timestamptz default now()
) returns date language plpgsql stable security definer set search_path='public'
as $$
declare v_override date;v_tz text:='Asia/Bangkok';v_cut time:='16:30';v_local timestamp;v_day date;v_time time;
begin
 if nullif(trim(p_tenant),'') is null then raise exception 'tenant_required'; end if;
 select round_date_override,coalesce(timezone,'Asia/Bangkok'),coalesce(round_rollover_time,'16:30')
 into v_override,v_tz,v_cut from public.lekhub_settings where tenant_key=p_tenant and id=true;
 if v_override is not null then return v_override; end if;
 v_local:=p_at at time zone v_tz;v_day:=v_local::date;v_time:=v_local::time;
 if extract(day from v_day)::int=1 then
  if v_time<v_cut then return v_day; else return v_day+15; end if;
 elsif extract(day from v_day)::int between 2 and 15 then
  return date_trunc('month',v_day)::date+15;
 elsif extract(day from v_day)::int=16 then
  if v_time<v_cut then return v_day; else return (date_trunc('month',v_day)+interval '1 month')::date; end if;
 else
  return (date_trunc('month',v_day)+interval '1 month')::date;
 end if;
end $$;

create or replace function public.get_lekhub_public_status_v2(p_channel_id text)
returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_tenant text;v public.lekhub_settings%rowtype;v_blocked jsonb;v_round date;
begin
 v_tenant:=public.lekhub_tenant_from_channel(p_channel_id,true);
 select * into v from public.lekhub_settings where tenant_key=v_tenant and id=true;
 if not found then raise exception 'tenant_settings_missing'; end if;
 select coalesce(jsonb_agg(item_value order by item_value),'[]'::jsonb)
 into v_blocked from public.lekhub_blocked_values
 where tenant_key=v_tenant and active=true;
 v_round:=public.lekhub_effective_round_date_for_tenant(v_tenant,now());
 return jsonb_build_object(
  'success',true,'tenant_key',v_tenant,
  'is_open',v.accepting and ((now() at time zone v.timezone)::time<v.close_time),
  'close_time',v.close_time,'cash_percent',v.cash_percent,
  'blocked_enabled',v.blocked_enabled,
  'blocked_values',case when v.blocked_enabled then v_blocked else '[]'::jsonb end,
  'round_date',v_round,'previous_round_number',v.previous_round_number
 );
end $$;

