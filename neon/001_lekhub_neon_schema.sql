 into v_rows from public.lekhub_line_admin_requests r
 join public.lekhub_tenants t on t.tenant_key=r.tenant_key;
 return jsonb_build_object('ok',true,'rows',v_rows);
end $$;

create or replace function public.lekhub_owner_approve_admin_request(
 p_token text,p_tenant_key text,p_line_user_id text
) returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_session jsonb;v_req public.lekhub_line_admin_requests%rowtype;
begin
 v_session:=public.lekhub_check_line_admin_session(p_token);
 if coalesce((v_session->>'ok')::boolean,false) is not true or
    coalesce(v_session->>'role','') not in ('owner','super_admin') then raise exception 'owner_required';end if;
 select * into v_req from public.lekhub_line_admin_requests
 where tenant_key=p_tenant_key and line_user_id=p_line_user_id;
 if not found then raise exception 'request_not_found';end if;
 insert into public.lekhub_line_admins(tenant_key,line_user_id,display_name,picture_url,role,is_active)
 values(v_req.tenant_key,v_req.line_user_id,v_req.display_name,v_req.picture_url,'admin',true)
 on conflict(tenant_key,line_user_id) do update set
  display_name=excluded.display_name,picture_url=excluded.picture_url,role='admin',is_active=true;
 delete from public.lekhub_line_admin_requests
 where tenant_key=p_tenant_key and line_user_id=p_line_user_id;
 return jsonb_build_object('ok',true,'tenant_key',p_tenant_key,'line_user_id',p_line_user_id);
end $$;

create or replace function public.lekhub_owner_update_tenant(
 p_token text,p_tenant_key text,p_patch jsonb
) returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_session jsonb;v_row public.lekhub_tenants%rowtype;v_status text;v_extend int;v_expires timestamptz;v_ready boolean;
begin
 v_session:=public.lekhub_check_line_admin_session(p_token);
 if coalesce((v_session->>'ok')::boolean,false) is not true or
    coalesce(v_session->>'role','') not in ('owner','super_admin') then raise exception 'owner_required';end if;
 if p_tenant_key='platform' then raise exception 'platform_tenant_locked';end if;
 if p_patch?'status' then
  v_status:=p_patch->>'status';
  if v_status not in ('active','locked','expired') then raise exception 'invalid_status';end if;
 end if;
 if p_patch?'extendDays' then
  v_extend:=greatest(1,least(365,coalesce((p_patch->>'extendDays')::int,30)));
  select (case when expires_at is not null and expires_at>now() then expires_at else now() end)+make_interval(days=>v_extend)
  into v_expires from public.lekhub_tenants where tenant_key=p_tenant_key;
 end if;
 if p_patch?'isolationReady' then
  v_ready:=coalesce((p_patch->>'isolationReady')::boolean,false);
  if v_ready and not exists(
   select 1 from public.lekhub_tenant_secrets
   where tenant_key=p_tenant_key and nullif(trim(line_channel_access_token),'') is not null
  ) then raise exception 'tenant_line_token_required';end if;
 end if;
 update public.lekhub_tenants t set
  display_name=case when p_patch?'displayName' then coalesce(nullif(trim(p_patch->>'displayName'),''),t.display_name) else t.display_name end,
  line_channel_id=case when p_patch?'lineChannelId' then nullif(trim(p_patch->>'lineChannelId'),'') else t.line_channel_id end,
  line_liff_id=case when p_patch?'lineLiffId' then nullif(trim(p_patch->>'lineLiffId'),'') else t.line_liff_id end,
  expires_at=case when p_patch?'extendDays' then v_expires when p_patch?'expiresAt' then nullif(p_patch->>'expiresAt','')::timestamptz else t.expires_at end,
  status=case when p_patch?'status' then v_status when p_patch?'extendDays' or p_patch?'expiresAt' then 'active' else t.status end,
  locked_at=case when p_patch?'status' and v_status='locked' then now()
                 when p_patch?'status' and v_status<>'locked' then null
                 when p_patch?'extendDays' or p_patch?'expiresAt' then null else t.locked_at end,
  isolation_ready=case when p_patch?'isolationReady' then v_ready else t.isolation_ready end,
  isolation_ready_at=case when p_patch?'isolationReady' and v_ready then now()
                          when p_patch?'isolationReady' and not v_ready then null else t.isolation_ready_at end,
  updated_at=now()
 where t.tenant_key=p_tenant_key returning * into v_row;
 if not found then raise exception 'tenant_not_found';end if;
 return jsonb_build_object('ok',true,'row',to_jsonb(v_row));
end $$;

create or replace function public.lekhub_purge_expired_history(p_at timestamptz default now())
returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v record;v_cutoff date;v_deleted int:=0;v_n int;
begin
 for v in
  select t.tenant_key,s.timezone,s.history_retention_days
  from public.lekhub_tenants t join public.lekhub_settings s on s.tenant_key=t.tenant_key
  where t.tenant_key<>'platform'
 loop
  v_cutoff:=((p_at at time zone v.timezone)::date-v.history_retention_days);
  delete from public.lekhub_activity_rewards where tenant_key=v.tenant_key and round_date<v_cutoff;
  delete from public.lekhub_backoffice_reports where tenant_key=v.tenant_key and round_date<v_cutoff;
  delete from public.lekhub_submissions where tenant_key=v.tenant_key and round_date<v_cutoff;
  get diagnostics v_n=row_count;v_deleted:=v_deleted+v_n;
 end loop;
 return jsonb_build_object('success',true,'deleted_submissions',v_deleted);
end $$;

