create or replace function public.lekhub_line_admin_login_v2(
 p_channel_id text,p_line_user_id text,p_display_name text,p_picture_url text default null
) returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_tenant text;v_role text;v_active boolean;v_token text;
begin
 v_tenant:=public.lekhub_tenant_from_channel(p_channel_id,true);
 if nullif(trim(p_line_user_id),'') is null or nullif(trim(p_display_name),'') is null then
  return jsonb_build_object('ok',false,'error','invalid_line_profile');
 end if;
 select role,is_active into v_role,v_active from public.lekhub_line_admins
 where tenant_key=v_tenant and line_user_id=p_line_user_id;
 if not found then
  insert into public.lekhub_line_admin_requests(tenant_key,line_user_id,display_name,picture_url,requested_at)
  values(v_tenant,p_line_user_id,p_display_name,p_picture_url,now())
  on conflict(tenant_key,line_user_id) do update
   set display_name=excluded.display_name,picture_url=excluded.picture_url,requested_at=now();
  return jsonb_build_object('ok',false,'error','line_user_not_admin');
 end if;
 if not coalesce(v_active,false) then return jsonb_build_object('ok',false,'error','line_user_not_admin'); end if;
 update public.lekhub_line_admins
 set display_name=p_display_name,picture_url=coalesce(p_picture_url,picture_url)
 where tenant_key=v_tenant and line_user_id=p_line_user_id;
 delete from public.lekhub_line_admin_sessions where expires_at<=now();
 v_token:=encode(gen_random_bytes(32),'hex');
 insert into public.lekhub_line_admin_sessions(token_hash,tenant_key,line_user_id,expires_at)
 values(encode(digest(v_token,'sha256'),'hex'),v_tenant,p_line_user_id,now()+interval '12 hours');
 return jsonb_build_object('ok',true,'session_token',v_token,'display_name',p_display_name,'role',v_role,'tenant_key',v_tenant);
end $$;

create or replace function public.lekhub_line_admin_get_settings(p_token text)
returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_session jsonb;v_tenant text;v public.lekhub_settings%rowtype;v_blocked jsonb;
begin
 v_session:=public.lekhub_check_line_admin_session(p_token);
 if coalesce((v_session->>'ok')::boolean,false) is not true then raise exception 'admin_required'; end if;
 v_tenant:=nullif(v_session->>'tenant_key','');
 if v_tenant is null then raise exception 'tenant_required'; end if;
 select * into v from public.lekhub_settings where tenant_key=v_tenant and id=true;
 select coalesce(jsonb_agg(item_value order by item_value),'[]'::jsonb) into v_blocked
 from public.lekhub_blocked_values where tenant_key=v_tenant and active=true;
 return jsonb_build_object(
  'success',true,'accepting',coalesce(v.accepting,true),'close_time',coalesce(v.close_time,'23:59'),
  'timezone',coalesce(v.timezone,'Asia/Bangkok'),'category_amounts',coalesce(v.category_amounts,'{}'),
  'cash_percent',coalesce(v.cash_percent,0),'blocked_enabled',coalesce(v.blocked_enabled,true),
  'blocked_values',v_blocked,'round_date_override',v.round_date_override,
  'previous_round_number',v.previous_round_number,'activity_prize_number',v.activity_prize_number,
  'activity_3front',v.activity_3front,'activity_3back',v.activity_3back,'activity_2bottom',v.activity_2bottom
 );
end $$;

create or replace function public.lekhub_line_admin_replace_blocked_values(p_token text,p_values text[])
returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_session jsonb;v_tenant text;v text;v_clean text;
begin
 v_session:=public.lekhub_check_line_admin_session(p_token);
 if coalesce((v_session->>'ok')::boolean,false) is not true then raise exception 'admin_required'; end if;
 v_tenant:=nullif(v_session->>'tenant_key','');
 if v_tenant is null then raise exception 'tenant_required'; end if;
 update public.lekhub_blocked_values set active=false,updated_at=now()
 where tenant_key=v_tenant and active=true;
 foreach v in array coalesce(p_values,array[]::text[]) loop
  v_clean:=regexp_replace(coalesce(v,''),'[^0-9]','','g');
  if v_clean<>'' then
   insert into public.lekhub_blocked_values(tenant_key,item_value,category,active,note,updated_at)
