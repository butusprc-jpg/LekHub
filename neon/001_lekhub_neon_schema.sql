create or replace function public.submit_lekhub_submission_v2(
 p_channel_id text,p_reference_code text,p_line_user_id text,p_member_name text,
 p_member_avatar text,p_items jsonb,p_attachment_url text default null
) returns jsonb language plpgsql security definer set search_path='public'
as $$
declare
 v_tenant text;v_submission_id uuid;v_count int;v_original_total numeric(14,2):=0;
 v_total numeric(14,2);v_item jsonb;v_order int:=0;v_value text;v_category text;
 v_label text;v_heart numeric;v_cash boolean:=false;v_item_cash boolean;
 v_settings public.lekhub_settings%rowtype;v_recent int;v_cash_percent numeric(5,2);v_round date;
begin
 v_tenant:=public.lekhub_tenant_from_channel(p_channel_id,true);
 if coalesce(trim(p_reference_code),'')='' or length(p_reference_code)>64 then raise exception 'invalid_reference'; end if;
 if coalesce(trim(p_line_user_id),'')='' then raise exception 'line_user_required'; end if;
 select * into v_settings from public.lekhub_settings where tenant_key=v_tenant and id=true;
 if not found then raise exception 'tenant_settings_missing'; end if;
 if not v_settings.accepting then raise exception 'not_accepting'; end if;
 if (now() at time zone v_settings.timezone)::time>=v_settings.close_time then raise exception 'outside_accepting_time'; end if;
 select count(*) into v_recent from public.lekhub_submissions
  where tenant_key=v_tenant and line_user_id=p_line_user_id and created_at>=now()-interval '60 seconds';
 if v_recent>=10 then raise exception 'rate_limited'; end if;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'items_required'; end if;
 if jsonb_array_length(p_items)>100 then raise exception 'too_many_items'; end if;
 v_count:=jsonb_array_length(p_items);
 for v_item in select * from jsonb_array_elements(p_items) loop
  v_value:=regexp_replace(coalesce(v_item->>'value',''),'[^0-9]','','g');
  v_category:=left(coalesce(v_item->>'category',''),32);
  if v_category not in ('3topmix','3top','3front','3back','2top','single','mix','bottom') then raise exception 'invalid_category'; end if;
  v_label:=left(coalesce(v_item->>'category_label',v_category),80);
  begin v_heart:=(v_item->>'heart')::numeric; exception when others then raise exception 'invalid_heart'; end;
  if v_value='' or length(v_value)>6 then raise exception 'invalid_item_value'; end if;
  if v_heart<=0 or v_heart>100000000 then raise exception 'invalid_heart'; end if;
  if v_settings.blocked_enabled and exists(
   select 1 from public.lekhub_blocked_values b
   where b.tenant_key=v_tenant and b.active and b.item_value=v_value
     and (b.category='' or b.category=v_category)
  ) then raise exception 'blocked_value'; end if;
  v_original_total:=v_original_total+v_heart;
  v_item_cash:=coalesce((v_item->>'cash')::boolean,false);
  if v_item_cash then v_cash:=true; end if;
 end loop;
 v_cash_percent:=case when v_cash then greatest(0,least(100,v_settings.cash_percent)) else 0 end;
 v_total:=round(v_original_total*(1-v_cash_percent/100.0),2);
 v_round:=public.lekhub_effective_round_date_for_tenant(v_tenant,now());
 insert into public.lekhub_submissions(
  tenant_key,reference_code,line_user_id,member_name,member_avatar,item_count,total,
  original_total,is_cash,cash_percent,attachment_url,round_date
 ) values(
  v_tenant,left(trim(p_reference_code),64),left(trim(p_line_user_id),128),
  left(coalesce(nullif(trim(p_member_name),''),'LINE Member'),120),
  left(nullif(trim(p_member_avatar),''),500),v_count,v_total,v_original_total,
  v_cash,v_cash_percent,left(nullif(trim(p_attachment_url),''),1000),v_round
 ) returning id into v_submission_id;
 for v_item in select * from jsonb_array_elements(p_items) loop
  v_order:=v_order+1;
  v_value:=regexp_replace(coalesce(v_item->>'value',''),'[^0-9]','','g');
  v_category:=left(coalesce(v_item->>'category',''),32);
  v_label:=left(coalesce(v_item->>'category_label',v_category),80);
  v_heart:=(v_item->>'heart')::numeric;
  v_item_cash:=coalesce((v_item->>'cash')::boolean,false);
  insert into public.lekhub_submission_items(
   tenant_key,submission_id,item_value,category,category_label,heart,sort_order,is_cash
  ) values(v_tenant,v_submission_id,v_value,v_category,v_label,v_heart,v_order,v_item_cash);
 end loop;
 return jsonb_build_object(
  'success',true,'tenant_key',v_tenant,'id',v_submission_id,
  'reference_code',p_reference_code,'item_count',v_count,'original_total',v_original_total,
  'total',v_total,'cash_percent',v_cash_percent,'is_cash',v_cash,'round_date',v_round,'status','pending'
 );
exception when unique_violation then
 return jsonb_build_object('success',false,'reason','duplicate_reference');
end $$;

create or replace function public.lekhub_check_line_admin_session(p_token text)
returns jsonb language plpgsql security definer set search_path='public'
as $$
declare v_row record;
begin
 if nullif(trim(p_token),'') is null then return jsonb_build_object('ok',false); end if;
 select a.line_user_id,a.display_name,a.role,a.tenant_key into v_row
 from public.lekhub_line_admin_sessions s
 join public.lekhub_line_admins a on a.tenant_key=s.tenant_key and a.line_user_id=s.line_user_id
 join public.lekhub_tenants t on t.tenant_key=s.tenant_key
 where s.token_hash=encode(digest(p_token,'sha256'),'hex')
   and s.expires_at>now() and a.is_active
   and t.status='active' and (t.expires_at is null or t.expires_at>now())
 limit 1;
 if not found then return jsonb_build_object('ok',false); end if;
 return jsonb_build_object(
  'ok',true,'user_id',v_row.line_user_id,'display_name',v_row.display_name,
  'role',v_row.role,'tenant_key',v_row.tenant_key
 );
end $$;

